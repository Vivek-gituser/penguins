"""Real PDF output built with ReportLab from a validated DocumentSpec.

Every visible string is XML-escaped before it reaches a flowable, so text
that came from an uploaded document or a model cannot inject markup into
the produced file. The security label is printed on every page because a
derived file never loses the classification of its source.
"""

import io
import re
from xml.sax.saxutils import escape

from reportlab.lib.colors import HexColor
from reportlab.lib.enums import TA_LEFT
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import (
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)

from tools.document_spec import DocumentSpec

PAGE_MARGIN = 18 * mm
PRIMARY = HexColor("#4f46e5")
SOFT = HexColor("#eef2ff")
TEXT = HexColor("#1f2937")
MUTED = HexColor("#6b7280")

LABEL_COLORS = {
    "PUBLIC": HexColor("#047857"),
    "INTERNAL": HexColor("#1d4ed8"),
    "CONFIDENTIAL": HexColor("#b45309"),
    "RESTRICTED": HexColor("#b91c1c"),
}


def safe_filename(title, suffix=".pdf", fallback="report"):
    """A downloadable name the user can read, never a path they control."""
    stem = re.sub(r"[^a-z0-9]+", "-", (title or "").lower()).strip("-")
    if not stem:
        stem = fallback
    return f"{stem[:60]}{suffix}"


def _styles():
    base = getSampleStyleSheet()
    return {
        "title": ParagraphStyle(
            "AgentgateTitle", parent=base["Title"], fontName="Helvetica-Bold",
            fontSize=24, leading=29, textColor=PRIMARY, alignment=TA_LEFT,
            spaceAfter=4,
        ),
        "subtitle": ParagraphStyle(
            "AgentgateSubtitle", parent=base["Normal"], fontSize=11,
            leading=15, textColor=MUTED, spaceAfter=12,
        ),
        "heading": ParagraphStyle(
            "AgentgateHeading", parent=base["Heading2"], fontName="Helvetica-Bold",
            fontSize=14, leading=18, textColor=TEXT, spaceBefore=14,
            spaceAfter=6,
        ),
        "body": ParagraphStyle(
            "AgentgateBody", parent=base["Normal"], fontSize=10.5,
            leading=15, textColor=TEXT, leftIndent=10, bulletIndent=2,
        ),
        "meta": ParagraphStyle(
            "AgentgateMeta", parent=base["Normal"], fontSize=9,
            leading=13, textColor=MUTED,
        ),
    }


def _decorate(canvas, doc, spec):
    page_color = LABEL_COLORS.get(spec.label, LABEL_COLORS["INTERNAL"])

    page_width, page_height = A4
    canvas.saveState()
    canvas.setFillColor(PRIMARY)
    canvas.rect(0, page_height - 8 * mm, page_width, 8 * mm, stroke=0, fill=1)

    canvas.setFillColor(page_color)
    canvas.rect(0, 0, page_width, 8 * mm, stroke=0, fill=1)

    canvas.setFillColor(HexColor("#ffffff"))
    canvas.setFont("Helvetica-Bold", 8)
    canvas.drawString(
        PAGE_MARGIN, 2.6 * mm, f"CLASSIFICATION: {spec.label}"
    )
    canvas.drawRightString(
        page_width - PAGE_MARGIN, 2.6 * mm,
        f"AGENTGATE  |  page {canvas.getPageNumber()}"
    )
    canvas.restoreState()


class _Report(SimpleDocTemplate):
    def __init__(self, buffer, spec, **kwargs):
        self.spec = spec
        super().__init__(buffer, pagesize=A4, **kwargs)

    def afterPage(self):
        _decorate(self.canv, self, self.spec)


def build_pdf(spec):
    """Return genuine PDF bytes for the given spec. Never writes a stub."""
    if not isinstance(spec, DocumentSpec):
        raise ValueError("A validated DocumentSpec is required")

    buffer = io.BytesIO()
    styles = _styles()

    document = _Report(
        buffer,
        spec,
        title=spec.title,
        author="AGENTGATE workspace",
        subject=f"{spec.transformation} export",
        leftMargin=PAGE_MARGIN,
        rightMargin=PAGE_MARGIN,
        topMargin=PAGE_MARGIN + 6 * mm,
        bottomMargin=PAGE_MARGIN + 6 * mm,
    )

    story = [
        Paragraph(escape(spec.title), styles["title"]),
    ]

    if spec.subtitle:
        story.append(Paragraph(escape(spec.subtitle), styles["subtitle"]))

    badge = Table(
        [[Paragraph(
            f"<font color='#ffffff'><b>{escape(spec.label)}</b></font>",
            styles["meta"],
        )]],
        colWidths=[36 * mm],
    )
    badge.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), LABEL_COLORS.get(
            spec.label, LABEL_COLORS["INTERNAL"])),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
        ("TOPPADDING", (0, 0), (-1, -1), 3),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
    ]))

    story += [
        Spacer(1, 4 * mm),
        badge,
        Spacer(1, 3 * mm),
        Paragraph(
            "Generated by AGENTGATE. Classification is inherited from the "
            "trusted source material and cannot be lowered by the AI model.",
            styles["meta"],
        ),
        Spacer(1, 6 * mm),
    ]

    for index, section in enumerate(spec.sections, start=1):
        story.append(Paragraph(
            escape(f"{index}. {section.heading}"), styles["heading"]
        ))
        for bullet in section.bullets:
            story.append(Paragraph(
                escape(bullet), styles["body"], bulletText="\u2022"
            ))
        story.append(Spacer(1, 2 * mm))

    document.build(story)
    payload = buffer.getvalue()

    if not payload.startswith(b"%PDF-") or len(payload) < 1000:
        raise ValueError("PDF generation did not produce a real document")

    return payload
